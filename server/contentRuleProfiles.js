export const CONTENT_RULE_PROFILES = {
  A: PROFILE_A,
  B: PROFILE_B,
}

export function resolveLiveContentRuleProfileId(topic) {
  return topic?.type === 'B型' ? 'B' : 'A'
}

export function resolveContentRuleProfile(profileId = DEFAULT_CONTENT_RULE_PROFILE_ID, topic = null) {
  const normalizedId = typeof profileId === 'string' ? profileId.trim().toUpperCase() : DEFAULT_CONTENT_RULE_PROFILE_ID

  if (!normalizedId || normalizedId === 'LIVE') {
    return CONTENT_RULE_PROFILES[resolveLiveContentRuleProfileId(topic)]
  }

  return CONTENT_RULE_PROFILES[normalizedId] ?? CONTENT_RULE_PROFILES[resolveLiveContentRuleProfileId(topic)]
}
